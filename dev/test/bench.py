import asyncio, pathlib
from playwright.async_api import async_playwright
ROOT = pathlib.Path('/home/claude/kuratsuku/dev'); OUT = ROOT/'test'/'shots'; OUT.mkdir(exist_ok=True)
html = (ROOT/'dist/touchline.html').read_text()
(ROOT/'test/page.html').write_text('<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><style>body{margin:0}[hidden]{display:none!important}</style></head><body>' + html + '</body></html>')
LZ = (ROOT/'test/vendor/lz-string.min.js').read_text()
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        ctx = await b.new_context(viewport={'width':390,'height':844}, device_scale_factor=2, has_touch=True)
        pg = await ctx.new_page(); errs = []
        pg.on('pageerror', lambda e: errs.append('PAGEERROR ' + str(e)))
        async def route(r):
            if 'lz-string' in r.request.url: await r.fulfill(status=200, content_type='application/javascript', body=LZ)
            else: await r.abort()
        await pg.route('https://**/*', route)
        await pg.goto('file://' + str(ROOT/'test/page.html')); await pg.wait_for_timeout(300)
        await pg.click('text=新しく始める'); await pg.click('[data-id="kashiwa"]'); await pg.wait_for_timeout(300)
        await pg.click('[data-act="nameClub"]'); await pg.wait_for_timeout(250); await pg.click('#sheet [data-act="startClub"]'); await pg.wait_for_timeout(300)
        await pg.click('[data-tab="tactics"]'); await pg.wait_for_timeout(200)
        bench0 = await pg.evaluate("[...document.querySelectorAll('[data-act=benchPick]')].map(e => e.dataset.id)")
        # swap the 3rd bench player for the first reserve
        await pg.click('[data-act="benchPick"] >> nth=2'); await pg.wait_for_timeout(400)
        await pg.screenshot(path=str(OUT/'b-sheet.png'))
        inId = await pg.evaluate("document.querySelector('#sheet [data-act=benchIn]:not([disabled])').dataset.id")
        await pg.click(f'#sheet [data-act="benchIn"][data-id="{inId}"]'); await pg.wait_for_timeout(400)
        bench1 = await pg.evaluate("[...document.querySelectorAll('[data-act=benchPick]')].map(e => e.dataset.id)")
        print('swapped in', inId, 'in bench now', inId in bench1, '| removed', bench0[2], 'gone', bench0[2] not in bench1, '| size', len(bench1))
        await pg.screenshot(path=str(OUT/'b-after.png'), full_page=False)
        # the choice must survive advancing to match day
        await pg.click('[data-act="go"]'); await pg.wait_for_timeout(400)
        await pg.click('#sheet [data-act="toTactics"]'); await pg.wait_for_timeout(300)
        bench2 = await pg.evaluate("[...document.querySelectorAll('[data-act=benchPick]')].map(e => e.dataset.id)")
        print('kept after advancing:', inId in bench2, '| size', len(bench2))
        # in-match substitution with the picked bench player
        await pg.click('[data-act="go"]'); await pg.wait_for_timeout(300)
        await pg.click('#sheet [data-act="kickoff"]'); await pg.wait_for_timeout(500)
        await pg.click('[data-act="mTac"]'); await pg.wait_for_timeout(400)
        await pg.click('#sheet [data-act="mOut"] >> nth=5'); await pg.wait_for_timeout(300)
        ins = await pg.evaluate("[...document.querySelectorAll('#sheet [data-act=mIn]')].map(e => e.dataset.id)")
        print('bench options in match include picked player:', inId in ins, len(ins))
        await pg.click(f'#sheet [data-act="mIn"][data-id="{inId}"]'); await pg.wait_for_timeout(300)
        await pg.screenshot(path=str(OUT/'b-match-sub.png'))
        left = await pg.evaluate("document.querySelector('#sheet [data-act=autoSubs] .small').textContent")
        await pg.click('#sheet [data-act="closeSheet"]'); await pg.wait_for_timeout(300)
        feed = await pg.evaluate("[...document.querySelectorAll('#feed li')].map(l => l.textContent).filter(t => t.includes('交代'))")
        print('subs left:', left, '| feed:', feed[:2])
        print('\n'.join(errs) or 'no errors')
        await b.close()
asyncio.run(main())
