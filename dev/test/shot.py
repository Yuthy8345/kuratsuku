import asyncio, sys, pathlib
from playwright.async_api import async_playwright
ROOT = pathlib.Path('/home/claude/kuratsuku/dev')
OUT = ROOT / 'test' / 'shots'; OUT.mkdir(exist_ok=True)
page_html = (ROOT/'dist/touchline.html').read_text()
wrapped = '<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover"><style>:root{color-scheme:light;padding-top:env(safe-area-inset-top);padding-bottom:env(safe-area-inset-bottom)}body{margin:0;font:14px system-ui}img{max-width:100%}[hidden]{display:none!important}</style></head><body>' + page_html + '</body></html>'
(ROOT/'test/page.html').write_text(wrapped)
LZ = (ROOT/'test/vendor/lz-string.min.js').read_text()
async def main():
    scheme = sys.argv[1] if len(sys.argv) > 1 else 'light'
    async with async_playwright() as p:
        b = await p.chromium.launch()
        ctx = await b.new_context(viewport={'width': 390, 'height': 844}, device_scale_factor=2, color_scheme=scheme, has_touch=True)
        page = await ctx.new_page()
        errs = []
        page.on('console', lambda m: errs.append(m.type + ': ' + m.text) if m.type in ('error', 'warning') else None)
        page.on('pageerror', lambda e: errs.append('PAGEERROR: ' + str(e)))
        async def route(r):
            if 'lz-string' in r.request.url: await r.fulfill(status=200, content_type='application/javascript', body=LZ)
            else: await r.abort()
        await page.route('https://**/*', route)
        await page.goto('file://' + str(ROOT/'test/page.html'))
        await page.wait_for_timeout(400)
        await page.screenshot(path=str(OUT/f'{scheme}-01-title.png'))
        await page.click('text=新しく始める'); await page.wait_for_timeout(200)
        await page.screenshot(path=str(OUT/f'{scheme}-02-select.png'))
        await page.click('[data-id="mito"]'); await page.wait_for_timeout(400)
        await page.screenshot(path=str(OUT/f'{scheme}-03-clubsheet.png'))
        await page.click('[data-act="nameClub"]'); await page.wait_for_timeout(250); await page.click('#sheet [data-act="startClub"]'); await page.wait_for_timeout(500)
        await page.screenshot(path=str(OUT/f'{scheme}-04-home.png'))
        await page.click('[data-act="go"]'); await page.wait_for_timeout(500)
        await page.screenshot(path=str(OUT/f'{scheme}-05-prematch.png'))
        await page.click('[data-act="kickoff"]'); await page.wait_for_timeout(300)
        await page.click('[data-act="mSpeed"]'); await page.click('[data-act="mSpeed"]')
        await page.wait_for_timeout(2600)
        await page.screenshot(path=str(OUT/f'{scheme}-06-match.png'))
        await page.click('[data-act="mTac"]'); await page.wait_for_timeout(400)
        await page.screenshot(path=str(OUT/f'{scheme}-07-mtac.png'))
        await page.click('#sheet [data-act="closeSheet"]'); await page.wait_for_timeout(300)
        await page.click('[data-act="mSkip"]'); await page.wait_for_timeout(400)
        await page.screenshot(path=str(OUT/f'{scheme}-08-result.png'))
        await page.click('[data-act="mClose"]'); await page.wait_for_timeout(300)
        await page.screenshot(path=str(OUT/f'{scheme}-09-home2.png'))
        for t in ['squad', 'tactics', 'league', 'club']:
            await page.click(f'[data-tab="{t}"]'); await page.wait_for_timeout(250)
            await page.screenshot(path=str(OUT/f'{scheme}-1{["squad","tactics","league","club"].index(t)}-{t}.png'))
        await page.click('[data-act="clView"][data-k="market"]'); await page.wait_for_timeout(250)
        await page.screenshot(path=str(OUT/f'{scheme}-14-market.png'))
        await page.click('#mk-list [data-act="player"] >> nth=0'); await page.wait_for_timeout(400)
        await page.screenshot(path=str(OUT/f'{scheme}-15-player.png'))
        await page.click('#sheet [data-act="closeSheet"]'); await page.wait_for_timeout(300)
        await page.click('[data-tab="tactics"]'); await page.wait_for_timeout(200)
        await page.click('.tok >> nth=9'); await page.wait_for_timeout(400)
        await page.screenshot(path=str(OUT/f'{scheme}-16-slot.png'))
        await page.click('#sheet [data-act="assign"] >> nth=3'); await page.wait_for_timeout(300)
        # advance several times quickly via quick sim
        for i in range(6):
            await page.click('[data-act="go"]'); await page.wait_for_timeout(250)
            if await page.locator('#sheet .card.alert').count():
                await page.click('#sheet [data-act="toTactics"]'); await page.wait_for_timeout(250); await page.click('[data-act="autoXI"]'); await page.wait_for_timeout(200)
                await page.click('[data-act="go"]'); await page.wait_for_timeout(300)
            if await page.locator('#sheet [data-act="quick"]').count():
                await page.click('#sheet [data-act="quick"]'); await page.wait_for_timeout(300)
                await page.click('[data-act="mClose"]'); await page.wait_for_timeout(200)
        await page.click('[data-tab="league"]'); await page.wait_for_timeout(200)
        await page.screenshot(path=str(OUT/f'{scheme}-17-league.png'))
        sw = await page.evaluate('document.documentElement.scrollWidth')
        saved = await page.evaluate('(localStorage.getItem("touchline.j1.save")||"").slice(0,3) + " len=" + (localStorage.getItem("touchline.j1.save")||"").length')
        print('scrollWidth', sw, 'save', saved)
        print('\n'.join(errs[:20]) or 'no console errors')
        await b.close()
asyncio.run(main())
